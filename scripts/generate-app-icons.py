#!/usr/bin/env python3
"""
Builds the ALG app icons from the official artwork in assets/brand/.

  assets/brand/app-icon.png     1024x1024, red mark on white (from the ALG iOS app)
  assets/brand/splash-logo.png  the red mark on transparent (also feeds the splash)

Android
  - adaptive icon (API 26+): white background + the mark as foreground, with
    a monochrome layer so Android 13+ themed icons work
  - legacy square and round icons for older devices
iOS
  - a single 1024x1024 universal icon (Xcode scales it to every size)

Run from the project root:  python3 scripts/generate-app-icons.py
The splash screen is generated separately by react-native-bootsplash:
  npx react-native-bootsplash generate assets/brand/splash-logo.png \
    --platforms=android,ios --background=#ffffff --logo-width=110 --assets-output=assets/bootsplash
"""
import json
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'android/app/src/main/res')
IOS_ICONSET = os.path.join(ROOT, 'ios/AlgEcommerce/Images.xcassets/AppIcon.appiconset')

APP_ICON = os.path.join(ROOT, 'assets/brand/app-icon.png')
MARK = os.path.join(ROOT, 'assets/brand/splash-logo.png')

WHITE = (255, 255, 255, 255)
# Launcher sizes per density: legacy icon (48dp) and adaptive layer (108dp).
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}


def mark():
    """The mark cropped to its visible pixels."""
    image = Image.open(MARK).convert('RGBA')
    return image.crop(image.getbbox())


def place(canvas_size, image, fraction, background=None):
    """`image` scaled to `fraction` of the canvas, centred."""
    canvas = Image.new('RGBA', (canvas_size, canvas_size), background or (0, 0, 0, 0))
    target = int(canvas_size * fraction)
    scale = target / max(image.size)
    resized = image.resize((max(1, round(image.size[0] * scale)), max(1, round(image.size[1] * scale))), Image.LANCZOS)
    canvas.alpha_composite(resized, ((canvas_size - resized.size[0]) // 2, (canvas_size - resized.size[1]) // 2))
    return canvas


def masked(image, shape):
    """`image` clipped to a rounded square ('square') or a circle ('round')."""
    size = image.size[0]
    supersample = 4
    mask = Image.new('L', (size * supersample, size * supersample), 0)
    draw = ImageDraw.Draw(mask)
    box = (0, 0, size * supersample - 1, size * supersample - 1)
    if shape == 'round':
        draw.ellipse(box, fill=255)
    else:
        draw.rounded_rectangle(box, radius=int(size * supersample * 0.22), fill=255)
    mask = mask.resize((size, size), Image.LANCZOS)
    out = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    out.paste(image, (0, 0), mask)
    return out


def android():
    logo = mark()
    for density, factor in DENSITIES.items():
        folder = os.path.join(RES, f'mipmap-{density}')
        os.makedirs(folder, exist_ok=True)

        # Legacy (pre-API 26): white tile with the mark, rounded square and circle.
        legacy = round(48 * factor)
        tile = place(legacy, logo, 0.62, WHITE)
        masked(tile, 'square').save(os.path.join(folder, 'ic_launcher.png'))
        masked(tile, 'round').save(os.path.join(folder, 'ic_launcher_round.png'))

        # Adaptive foreground: 108dp layer, the mark inside the 66dp safe zone.
        layer = round(108 * factor)
        place(layer, logo, 0.5).save(os.path.join(folder, 'ic_launcher_foreground.png'))

    anydpi = os.path.join(RES, 'mipmap-anydpi-v26')
    os.makedirs(anydpi, exist_ok=True)
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<!-- ALG launcher icon: generated by scripts/generate-app-icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""
    for name in ('ic_launcher.xml', 'ic_launcher_round.xml'):
        with open(os.path.join(anydpi, name), 'w') as handle:
            handle.write(adaptive)

    with open(os.path.join(RES, 'values/ic_launcher_background.xml'), 'w') as handle:
        handle.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
                     '    <color name="ic_launcher_background">#FFFFFF</color>\n</resources>\n')


def ios():
    icon = Image.open(APP_ICON).convert('RGB')  # the App Store rejects icons with alpha
    icon.resize((1024, 1024), Image.LANCZOS).save(os.path.join(IOS_ICONSET, 'AppIcon-1024.png'))
    contents = {
        'images': [
            {'filename': 'AppIcon-1024.png', 'idiom': 'universal', 'platform': 'ios', 'size': '1024x1024'},
        ],
        'info': {'author': 'xcode', 'version': 1},
    }
    with open(os.path.join(IOS_ICONSET, 'Contents.json'), 'w') as handle:
        json.dump(contents, handle, indent=2)
        handle.write('\n')


if __name__ == '__main__':
    android()
    ios()
    print('App icons generated.')
